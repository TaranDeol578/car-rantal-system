CREATE TABLE BRANCHES (
    BRANCH_ID NUMBER PRIMARY KEY,
    BRANCH_NAME VARCHAR2(50) NOT NULL,
    CITY VARCHAR2(40) NOT NULL,
    CONTACT_NO VARCHAR2(15)
);

CREATE TABLE CUSTOMERS (
    CUSTOMER_ID NUMBER PRIMARY KEY,
    CUSTOMER_NAME VARCHAR2(60) NOT NULL,
    PHONE VARCHAR2(15) NOT NULL,
    EMAIL VARCHAR2(70),
    LICENSE_NO VARCHAR2(30) UNIQUE NOT NULL
);

CREATE TABLE CARS (
    CAR_ID NUMBER PRIMARY KEY,
    BRAND VARCHAR2(40) NOT NULL,
    MODEL VARCHAR2(50) NOT NULL,
    REG_NO VARCHAR2(20) UNIQUE NOT NULL,
    CATEGORY VARCHAR2(20) NOT NULL,
    DAILY_RATE NUMBER(9,2) CHECK (DAILY_RATE > 0),
    STATUS VARCHAR2(20) NOT NULL
        CHECK (STATUS IN ('AVAILABLE', 'BOOKED', 'RENTED', 'MAINTENANCE')),
    BRANCH_ID NUMBER NOT NULL,
    FOREIGN KEY (BRANCH_ID) REFERENCES BRANCHES(BRANCH_ID)
);

CREATE TABLE BOOKINGS (
    BOOKING_ID NUMBER PRIMARY KEY,
    CUSTOMER_ID NUMBER NOT NULL,
    CAR_ID NUMBER NOT NULL,
    START_DATE DATE NOT NULL,
    END_DATE DATE NOT NULL,
    BOOKING_STATUS VARCHAR2(20) NOT NULL
        CHECK (BOOKING_STATUS IN ('CONFIRMED', 'COMPLETED', 'CANCELLED')),
    TOTAL_ESTIMATE NUMBER(10,2) CHECK (TOTAL_ESTIMATE >= 0),
    FOREIGN KEY (CUSTOMER_ID) REFERENCES CUSTOMERS(CUSTOMER_ID),
    FOREIGN KEY (CAR_ID) REFERENCES CARS(CAR_ID),
    CHECK (END_DATE >= START_DATE)
);

CREATE TABLE RENTALS (
    RENTAL_ID NUMBER PRIMARY KEY,
    BOOKING_ID NUMBER UNIQUE NOT NULL,
    PICKUP_DATE DATE NOT NULL,
    DUE_DATE DATE NOT NULL,
    ACTUAL_RETURN_DATE DATE,
    RENTAL_STATUS VARCHAR2(20) NOT NULL
        CHECK (RENTAL_STATUS IN ('ONGOING', 'RETURNED')),
    FOREIGN KEY (BOOKING_ID) REFERENCES BOOKINGS(BOOKING_ID),
    CHECK (DUE_DATE >= PICKUP_DATE),
    CHECK (ACTUAL_RETURN_DATE IS NULL OR ACTUAL_RETURN_DATE >= PICKUP_DATE)
);

CREATE TABLE PAYMENTS (
    PAYMENT_ID NUMBER PRIMARY KEY,
    RENTAL_ID NUMBER NOT NULL,
    AMOUNT NUMBER(10,2) CHECK (AMOUNT > 0),
    PAYMENT_DATE DATE NOT NULL,
    PAYMENT_METHOD VARCHAR2(15) NOT NULL
        CHECK (PAYMENT_METHOD IN ('UPI', 'CARD', 'CASH')),
    PAYMENT_STATUS VARCHAR2(15) NOT NULL
        CHECK (PAYMENT_STATUS IN ('PAID', 'PENDING')),
    FOREIGN KEY (RENTAL_ID) REFERENCES RENTALS(RENTAL_ID)
);

CREATE TABLE MAINTENANCE (
    MAINTENANCE_ID NUMBER PRIMARY KEY,
    CAR_ID NUMBER NOT NULL,
    SERVICE_DATE DATE NOT NULL,
    SERVICE_TYPE VARCHAR2(60) NOT NULL,
    COST NUMBER(10,2) CHECK (COST >= 0),
    FOREIGN KEY (CAR_ID) REFERENCES CARS(CAR_ID)
);

