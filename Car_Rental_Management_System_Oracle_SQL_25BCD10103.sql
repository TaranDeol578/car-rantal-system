-- REPORT QUERIES
-- QUERY 1. All cars in the fleet
SELECT CAR_ID, BRAND, MODEL, CATEGORY, DAILY_RATE, STATUS
FROM CARS
ORDER BY CAR_ID;

-- QUERY 2. Cars currently available
SELECT CAR_ID, BRAND, MODEL, DAILY_RATE
FROM CARS
WHERE STATUS = 'AVAILABLE'
ORDER BY DAILY_RATE;

-- QUERY 3. Booking and customer details
SELECT B.BOOKING_ID, C.CUSTOMER_NAME, V.MODEL,
       B.START_DATE, B.BOOKING_STATUS
FROM BOOKINGS B
JOIN CUSTOMERS C ON B.CUSTOMER_ID = C.CUSTOMER_ID
JOIN CARS V ON B.CAR_ID = V.CAR_ID
ORDER BY B.BOOKING_ID;

-- QUERY 4. Ongoing car rentals
SELECT R.RENTAL_ID, C.CUSTOMER_NAME, V.MODEL, R.DUE_DATE
FROM RENTALS R
JOIN BOOKINGS B ON R.BOOKING_ID = B.BOOKING_ID
JOIN CUSTOMERS C ON B.CUSTOMER_ID = C.CUSTOMER_ID
JOIN CARS V ON B.CAR_ID = V.CAR_ID
WHERE R.RENTAL_STATUS = 'ONGOING'
ORDER BY R.RENTAL_ID;

-- QUERY 5. Total received payments
SELECT SUM(AMOUNT) AS TOTAL_PAID_REVENUE
FROM PAYMENTS
WHERE PAYMENT_STATUS = 'PAID';

-- QUERY 6. Collection by payment method
SELECT PAYMENT_METHOD, COUNT(*) AS PAYMENT_COUNT,
       SUM(AMOUNT) AS RECEIVED_AMOUNT
FROM PAYMENTS
WHERE PAYMENT_STATUS = 'PAID'
GROUP BY PAYMENT_METHOD
ORDER BY PAYMENT_METHOD;

-- QUERY 7. Branch-wise number of cars
SELECT B.BRANCH_NAME, COUNT(C.CAR_ID) AS TOTAL_CARS
FROM BRANCHES B
LEFT JOIN CARS C ON B.BRANCH_ID = C.BRANCH_ID
GROUP BY B.BRANCH_ID, B.BRANCH_NAME
ORDER BY B.BRANCH_ID;

-- QUERY 8. Car-wise maintenance costs
SELECT C.CAR_ID, C.MODEL, SUM(M.COST) AS SERVICE_COST
FROM MAINTENANCE M
JOIN CARS C ON M.CAR_ID = C.CAR_ID
GROUP BY C.CAR_ID, C.MODEL
ORDER BY C.CAR_ID;

-- QUERY 9. Booking status summary
SELECT BOOKING_STATUS, COUNT(*) AS TOTAL_BOOKINGS
FROM BOOKINGS
GROUP BY BOOKING_STATUS
ORDER BY BOOKING_STATUS;

-- QUERY 10. Pending payments
SELECT C.CUSTOMER_NAME, B.BOOKING_ID, P.AMOUNT AS PENDING_AMOUNT
FROM PAYMENTS P
JOIN RENTALS R ON P.RENTAL_ID = R.RENTAL_ID
JOIN BOOKINGS B ON R.BOOKING_ID = B.BOOKING_ID
JOIN CUSTOMERS C ON B.CUSTOMER_ID = C.CUSTOMER_ID
WHERE P.PAYMENT_STATUS = 'PENDING';

-- QUERY 11. Cars with no booking history
SELECT C.CAR_ID, C.BRAND, C.MODEL
FROM CARS C
LEFT JOIN BOOKINGS B ON C.CAR_ID = B.CAR_ID
WHERE B.BOOKING_ID IS NULL;

-- QUERY 12. Confirmed upcoming/active bookings
SELECT BOOKING_ID, CAR_ID, START_DATE, END_DATE,
       TOTAL_ESTIMATE
FROM BOOKINGS
WHERE BOOKING_STATUS = 'CONFIRMED'
  AND END_DATE >= DATE '2026-10-28'
ORDER BY START_DATE;
